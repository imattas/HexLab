#!/usr/bin/env python3
"""Generate the fixed Windows-936/GBK pair table from Unicode CP936.TXT."""

from __future__ import annotations

import argparse
import hashlib
import urllib.request
from pathlib import Path


SOURCE_URL = (
    "https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/CP936.TXT"
)
SOURCE_SHA256 = "b86f601c575e9ab457380b6f7abef03c75499cc6075bdc8b4b27f3f2de74bf6a"
LEAD_MIN, LEAD_MAX = 0x81, 0xFE
TRAILS = tuple(range(0x40, 0x7F)) + tuple(range(0x80, 0xFF))
TRAIL_INDEX = {trail: index for index, trail in enumerate(TRAILS)}
EXPECTED_ASSIGNED_PAIRS = 21_791


def source_bytes(path: Path | None) -> bytes:
    if path is not None:
        return path.read_bytes()
    with urllib.request.urlopen(SOURCE_URL, timeout=30) as response:
        return response.read()


def parse_mapping(data: bytes) -> list[int]:
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise SystemExit("CP936.TXT SHA-256 does not match the pinned source")

    text = data.decode("ascii")
    if "Table version: 2.01" not in text or "Date:          1/7/2000" not in text:
        raise SystemExit("CP936.TXT header does not match the pinned table version")

    table = [0] * ((LEAD_MAX - LEAD_MIN + 1) * len(TRAILS))
    assigned = set()
    for line in text.splitlines():
        fields = line.split("#", 1)[0].split()
        if len(fields) < 2 or not fields[0].startswith("0x") or not fields[1].startswith("0x"):
            continue
        source = int(fields[0], 16)
        scalar = int(fields[1], 16)
        if source < 0x100 or not (LEAD_MIN <= source >> 8 <= LEAD_MAX):
            continue
        lead, trail = source >> 8, source & 0xFF
        if trail not in TRAIL_INDEX:
            continue
        if scalar > 0xFFFF or 0xD800 <= scalar <= 0xDFFF:
            raise SystemExit(f"CP936 pair {source:04X} is not a BMP Unicode scalar")
        index = (lead - LEAD_MIN) * len(TRAILS) + TRAIL_INDEX[trail]
        if index in assigned:
            raise SystemExit(f"duplicate CP936 source pair {source:04X}")
        table[index] = scalar
        assigned.add(index)

    if len(assigned) != EXPECTED_ASSIGNED_PAIRS:
        raise SystemExit(
            f"expected {EXPECTED_ASSIGNED_PAIRS} assigned pairs, found {len(assigned)}"
        )
    return table


def render(table: list[int]) -> str:
    lines = [
        "// Generated by tools/generate_gbk_table.py from Unicode Consortium CP936.TXT",
        "// (table version 2.01, SHA-256 B86F601C575E9AB457380B6F7ABEF03C75499CC6075BDC8B4B27F3F2DE74BF6A).",
        "// Zero marks an unmapped or unassigned pair; 21,791 assigned pairs are present.",
        "static constexpr std::uint16_t gbk_pair_table[126 * 190] = {",
    ]
    for start in range(0, len(table), 10):
        lines.append("    " + ", ".join(f"0x{value:04x}" for value in table[start : start + 10]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source", type=Path, help="local CP936.TXT; defaults to the pinned Unicode URL"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("libs/analysis/src/strings_gbk_table.inc"),
        help="generated include path",
    )
    args = parser.parse_args()
    table = parse_mapping(source_bytes(args.source))
    args.output.write_text(render(table), encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
